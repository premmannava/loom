/**
 * Writes the website's generated pages from the component definitions and
 * the guide builder, so the site never repeats them by hand:
 *
 *   site/docs/components/*.md     the component reference, one page per category
 *   site/.generated/guide-*.md    the compact model guide and guide sizes
 *
 *   npm run site:docs
 *
 * The outputs are ignored by git and rebuilt by `npm run site:dev` and
 * `npm run site:build`. Edit a ComponentDef in src/components, never these pages.
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { coreComponents } from "../src/components";
import { mapComponents } from "../src/components/map";
import { CATEGORIES, COMMON_PROPS, type Category, type ComponentDef } from "../src/component";
import { componentExampleSpec, describeGuide, languageGuide, type GuideOptions } from "../src/prompt";
import { PROFILES } from "../src/profiles";
import { EXPRESSION_FUNCTIONS } from "../src/expr";
import { Registry } from "../src/registry";
import { componentSection } from "./component-docs";

const SITE = resolve(__dirname, "../site");
const COMPONENTS_DIR = resolve(SITE, "docs/components");
const GENERATED_DIR = resolve(SITE, ".generated");
const NOTICE = "<!-- Generated by scripts/gen-site-docs.ts from src/components. Edit the ComponentDef, not this file. -->";

const all: ComponentDef[] = [...coreComponents, ...mapComponents];
const registry = new Registry(all);
const categoryOf = new Map(all.map((c) => [c.type, c.category] as const));

const TITLES: Record<Category, string> = {
  layout: "Layout",
  content: "Content",
  data: "Data",
  input: "Input",
  navigation: "Navigation",
  feedback: "Feedback",
};
const INTROS: Record<Category, string> = {
  layout: "Containers that place other elements, plus `each`, which repeats elements once per item of a list.",
  content: "Text, images, code, badges and avatars.",
  data: "Figures, ratings, charts, tables and the world map. `map` and `pin` ship in the separate `loom-ui/map` entry point because the country outlines add about 76 KB.",
  input: "Controls people press, type into or drag. Most read and write a state name through `bind=`.",
  navigation: "Screens, tabs, breadcrumbs and pagination.",
  feedback: "Progress, loading placeholders and empty states.",
};

/** A link to a component's section on its category page, or code for names that aren't components (like root). */
function link(from: Category) {
  return (type: string) => {
    const cat = categoryOf.get(type);
    if (!cat) return `\`${type}\``;
    return cat === from ? `[\`${type}\`](#${type})` : `[\`${type}\`](./${cat}#${type})`;
  };
}

function categoryPage(cat: Category, defs: ComponentDef[]): string {
  const common = Object.keys(COMMON_PROPS).map((p) => `<code>${p}=</code>`).join(", ");
  return [
    "---",
    `title: ${TITLES[cat]} components`,
    `description: Reference for SayShape's ${TITLES[cat].toLowerCase()} components, generated from their definitions.`,
    "editLink: false",
    "---",
    NOTICE,
    "",
    `# ${TITLES[cat]} components`,
    "",
    INTROS[cat],
    "",
    `<p class="generated-note">Generated from the component definitions in <code>src/components</code>, the same source the parser validates against and the model guide is built from. Every element also accepts ${common}. Each example below is rendered live by the SayShape engine.</p>`,
    "",
    // Examples with images point at files this site doesn't have, so they're shown but not rendered.
    defs.map((c) => componentSection(c, { fence: /^\s*image\b/m.test(c.example ?? "") ? "loom" : "loom live", link: link(cat), example: (d) => d.example && componentExampleSpec(d, all).trimEnd() })).join("").trim(),
    "",
  ].join("\n");
}

function indexPage(): string {
  const rows = CATEGORIES.map((cat) => {
    const defs = all.filter((c) => c.category === cat);
    return `| [${TITLES[cat]}](./${cat}) | ${defs.map((d) => `[\`${d.type}\`](./${cat}#${d.type})`).join(", ")} |`;
  });
  return [
    "---",
    "title: Components",
    "description: Every component SayShape renders, generated from the component definitions.",
    "editLink: false",
    "---",
    NOTICE,
    "",
    "# Components",
    "",
    `SayShape ships ${all.length} components. Each one is a single \`ComponentDef\` in \`src/components\`: its description, props, allowed values, children and example live there, and this reference, the parser's validation and the model guide are all generated from it. A spec can't add components; they're reviewed TypeScript code.`,
    "",
    "| Category | Components |",
    "|---|---|",
    ...rows,
    "",
    "## Conventions",
    "",
    "- `\"text\"` is the quoted text after the element name: `button \"Save\"`.",
    "- A prop marked **required** must be given, or the parser reports it.",
    "- `state` props take a state name or a path like `t.done`; `action` props take `on=` strings; `condition` props take an expression.",
    "- Enum values are listed in the type column. Any other value is a warning and the prop falls back to its default.",
    "- Specs never set colors, fonts or pixel sizes. Roles such as `tone=`, `variant=` and `style=` pick from the theme.",
    "",
  ].join("\n");
}

function guideSizes(): string {
  const configs: Array<[string, GuideOptions]> = [
    ["full (default)", {}],
    ["full, no component examples", { examples: false }],
    ...Object.keys(PROFILES).map((p): [string, GuideOptions] => [`full, profile \`${p}\``, { profile: p }]),
    ["compact", { mode: "compact" }],
    ...Object.keys(PROFILES).map((p): [string, GuideOptions] => [`compact, profile \`${p}\``, { mode: "compact", profile: p }]),
  ];
  const rows = configs.map(([name, opts]) => {
    const info = describeGuide(registry, opts);
    return `| ${name} | ${info.components.length} | ${info.chars.toLocaleString("en-US")} | ~${info.estimatedTokens.toLocaleString("en-US")} |`;
  });
  return [
    NOTICE,
    "",
    "| Guide | Elements described | Characters | Tokens (estimated) |",
    "|---|---|---|---|",
    ...rows,
    "",
    "Token figures are characters divided by 4, a rough estimate rather than a tokenizer count. They're computed from the current component definitions when the site is built.",
    "",
  ].join("\n");
}

function compactGuide(): string {
  return [NOTICE, "", "```text", languageGuide(registry, { mode: "compact" }), "```", ""].join("\n");
}

mkdirSync(COMPONENTS_DIR, { recursive: true });
mkdirSync(GENERATED_DIR, { recursive: true });
// Remove pages for categories that no longer exist.
for (const f of readdirSync(COMPONENTS_DIR)) if (f.endsWith(".md")) rmSync(resolve(COMPONENTS_DIR, f));

writeFileSync(resolve(COMPONENTS_DIR, "index.md"), indexPage());
for (const cat of CATEGORIES) {
  const defs = all.filter((c) => c.category === cat);
  if (defs.length) writeFileSync(resolve(COMPONENTS_DIR, `${cat}.md`), categoryPage(cat, defs));
}
writeFileSync(resolve(GENERATED_DIR, "guide-sizes.md"), guideSizes());
writeFileSync(resolve(GENERATED_DIR, "functions.md"), [NOTICE, "", [...EXPRESSION_FUNCTIONS].sort().map((f) => `\`${f}\``).join(", "), ""].join("\n"));
writeFileSync(resolve(GENERATED_DIR, "guide-compact.md"), compactGuide());
console.log(`Wrote the reference for ${all.length} components and the model guide pages.`);
